export function hasZkuLesson(id: string): boolean {
  return Object.prototype.hasOwnProperty.call(LOADERS, id)
}

// Returns the lesson for a route id, falling back to the demo lesson for unknown ids.
export async function getZkuLesson(id: string): Promise<FullLesson> {
  const load = hasZkuLesson(id) ? LOADERS[id] : () => import('./data/_demo.json')
  const mod = await load()
  // JSON imports widen literal unions (e.g. 'true' | 'false') to string
  return mod.default as FullLesson
}
